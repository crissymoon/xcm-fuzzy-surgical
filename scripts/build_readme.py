#!/usr/bin/env python3
"""Render README.md from meta/project.json.

The JSON file is the single source of truth for documentation content. Run this
script after editing it, or use --check before committing to reject a stale README.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_METADATA = ROOT / "meta" / "project.json"
DEFAULT_OUTPUT = ROOT / "README.md"
PACKAGE_INIT = ROOT / "fuzzy_surgical" / "__init__.py"
MARKER = (
    "<!-- Generated by scripts/build_readme.py from meta/project.json. "
    "Do not edit by hand. -->"
)

REQUIRED_KEYS = (
    "schema_version",
    "name",
    "display_name",
    "version",
    "tagline",
    "summary",
    "author",
    "repository",
    "license",
    "python",
    "platforms",
    "highlights",
    "install",
    "quickstart",
    "cli",
    "controls",
    "safety",
    "development",
    "requirements",
    "community",
    "links",
)


class MetadataError(RuntimeError):
    """Raised when the metadata or version source is invalid."""


def _read_json(path: Path) -> Dict[str, Any]:
    try:
        with path.open("r", encoding="utf-8") as handle:
            data = json.load(handle)
    except FileNotFoundError as exc:
        raise MetadataError(f"metadata file not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise MetadataError(f"invalid JSON in {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise MetadataError(f"{path} must contain a JSON object")
    return data


def _package_version(path: Path = PACKAGE_INIT) -> str:
    try:
        source = path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise MetadataError(f"package version file not found: {path}") from exc
    tree = ast.parse(source, filename=str(path))
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id == "__version__":
                value = node.value
                if isinstance(value, ast.Constant) and isinstance(value.value, str):
                    return value.value
    raise MetadataError(f"__version__ not found in {path}")


def _require_mapping(data: Dict[str, Any], key: str) -> Dict[str, Any]:
    value = data.get(key)
    if not isinstance(value, dict):
        raise MetadataError(f"'{key}' must be an object")
    return value


def validate(metadata: Dict[str, Any], version: str) -> None:
    missing = [key for key in REQUIRED_KEYS if key not in metadata]
    if missing:
        raise MetadataError("missing metadata keys: " + ", ".join(missing))
    if metadata["version"] != version:
        raise MetadataError(
            f"version mismatch: meta/project.json has {metadata['version']!r} "
            f"but fuzzy_surgical/__init__.py has {version!r}"
        )
    author = _require_mapping(metadata, "author")
    if not author.get("name") or not author.get("website"):
        raise MetadataError("'author' requires name and website")
    license_info = _require_mapping(metadata, "license")
    if license_info.get("spdx") != "MIT":
        raise MetadataError("'license.spdx' must be MIT")
    repository = _require_mapping(metadata, "repository")
    for key in ("url", "web_url", "slug"):
        if not repository.get(key):
            raise MetadataError(f"'repository.{key}' is required")
    if not isinstance(metadata["highlights"], list) or not metadata["highlights"]:
        raise MetadataError("'highlights' must be a non-empty list")
    for section in ("install", "quickstart", "cli", "safety", "development"):
        _require_mapping(metadata, section)
    if not isinstance(metadata["controls"], list) or not metadata["controls"]:
        raise MetadataError("'controls' must be a non-empty list")


def _cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def _table(headers: Sequence[str], rows: Iterable[Sequence[Any]]) -> str:
    lines = [
        "| " + " | ".join(_cell(header) for header in headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(_cell(cell) for cell in row) + " |")
    return "\n".join(lines)


def _bullets(items: Iterable[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


def _code_block(language: str, commands: Sequence[str]) -> str:
    return "```" + language + "\n" + "\n".join(commands) + "\n```"


def _badges(metadata: Dict[str, Any]) -> str:
    repository = metadata["repository"]["web_url"]
    python_requires = metadata["python"]["requires"]
    website = metadata["links"]["website"]
    website_host = urlparse(website).netloc or website
    return "\n".join(
        [
            f"[![License: MIT](https://img.shields.io/badge/license-MIT-blue.svg)]"
            f"({repository}/blob/main/LICENSE)",
            f"[![Python {python_requires}+](https://img.shields.io/badge/python-"
            f"{python_requires}%2B-blue.svg)]({repository})",
            f"[![Website](https://img.shields.io/badge/website-{website_host}-black.svg)]"
            f"({website})",
        ]
    )


def _render_install(section: Dict[str, Any]) -> List[str]:
    lines: List[str] = ["## Installation", "", str(section.get("intro", "")).strip(), ""]
    for block in section["blocks"]:
        lines.extend(
            [
                f"### {block['title']}",
                "",
                _code_block(block.get("language", "bash"), block["commands"]),
                "",
            ]
        )
        for note in block.get("notes", []):
            lines.append(f"- {note}")
        if block.get("options"):
            lines.extend(["", "Installer options:", ""])
            for option in block["options"]:
                lines.append(f"- `{option['command']}`: {option['description']}")
        lines.append("")
    return lines


def _render_usage(section: Dict[str, Any], cli: Dict[str, Any]) -> List[str]:
    lines: List[str] = ["## Quick start", "", str(section.get("intro", "")).strip(), ""]
    lines.append(_code_block("bash", section["commands"]))
    lines.extend(["", "## Command line", "", str(cli.get("intro", "")).strip(), ""])
    lines.append(_table(cli["columns"], cli["rows"]))
    lines.append("")
    return lines


def _render_controls(controls: List[Dict[str, Any]]) -> List[str]:
    lines: List[str] = ["## TUI controls", ""]
    for group in controls:
        lines.extend([f"### {group['view']}", "", _table(["Key", "Action"], group["items"]), ""])
    return lines


def _render_devbox(section: Dict[str, Any]) -> List[str]:
    if not section:
        return []
    lines: List[str] = [
        "## Language server and dev box",
        "",
        str(section.get("intro", "")).strip(),
        "",
    ]
    if section.get("example"):
        if section.get("example_path"):
            lines.extend([f"`{section['example_path']}`", ""])
        lines.extend([_code_block(section.get("language", "json"), section["example"]), ""])
    if section.get("servers"):
        lines.extend(
            [
                _table(
                    ["Language", "Server", "Linter"],
                    section["servers"],
                ),
                "",
            ]
        )
    lines.extend(_bullets(section.get("notes", [])).splitlines())
    lines.append("")
    return lines


def _render_safety(section: Dict[str, Any]) -> List[str]:
    lines: List[str] = [
        "## Safety and limits",
        "",
        str(section.get("intro", "")).strip(),
        "",
        _table(["Limit", "Default"], section["limits"]),
        "",
    ]
    lines.extend(_bullets(section.get("notes", [])).splitlines())
    lines.append("")
    return lines


def _render_development(section: Dict[str, Any]) -> List[str]:
    lines: List[str] = ["## Development", "", str(section.get("intro", "")).strip(), ""]
    lines.extend(
        [
            "Linux and macOS:",
            "",
            _code_block("bash", section["commands"]),
            "",
            "Windows PowerShell:",
            "",
            _code_block("powershell", section["windows_commands"]),
            "",
        ]
    )
    lines.extend(_bullets(section.get("notes", [])).splitlines())
    lines.append("")
    return lines


def _render_requirements(rows: List[Sequence[str]]) -> List[str]:
    return [
        "## Requirements",
        "",
        _table(["Component", "Requirement"], rows),
        "",
    ]


def _render_footer(metadata: Dict[str, Any]) -> List[str]:
    community = metadata["community"]
    license_info = metadata["license"]
    author = metadata["author"]
    links = metadata["links"]
    return [
        "## Contributing",
        "",
        str(community.get("intro", "")).strip(),
        "",
        str(community.get("security", "")).strip(),
        "",
        "## License",
        "",
        f"{license_info['summary']} See [LICENSE](LICENSE) for the full text.",
        "",
        "## Author",
        "",
        f"{author['name']} - [{author['website']}]({author['website']})",
        "",
        f"Repository: [{links['repository']}]({links['repository']})",
        "",
    ]


def render(metadata: Dict[str, Any], version: str) -> str:
    validate(metadata, version)
    platforms = metadata["platforms"]
    lines: List[str] = [
        MARKER,
        "",
        f"# {metadata['display_name']}",
        "",
        _badges(metadata),
        "",
        metadata["tagline"],
        "",
        metadata["summary"],
        "",
        platforms["intro"],
        "",
        _table(
            ["Platform", "Notes"],
            [[item["name"], item["notes"]] for item in platforms["items"]],
        ),
        "",
        "## Features",
        "",
        _bullets(metadata["highlights"]),
        "",
    ]
    lines.extend(_render_install(metadata["install"]))
    lines.extend(_render_usage(metadata["quickstart"], metadata["cli"]))
    lines.extend(_render_controls(metadata["controls"]))
    lines.extend(_render_devbox(metadata.get("devbox", {})))
    lines.extend(_render_safety(metadata["safety"]))
    lines.extend(_render_development(metadata["development"]))
    lines.extend(_render_requirements(metadata["requirements"]))
    lines.extend(_render_footer(metadata))
    text = "\n".join(lines).rstrip() + "\n"
    return text.replace("\n\n\n", "\n\n")


def _write_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", newline="\n", dir=str(path.parent), delete=False
    )
    try:
        with handle:
            handle.write(content)
        os.replace(handle.name, path)
    except BaseException:
        try:
            os.unlink(handle.name)
        except OSError:
            pass
        raise


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate README.md from project metadata.")
    parser.add_argument("--metadata", type=Path, default=DEFAULT_METADATA)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail when README.md is stale")
    parser.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = parser.parse_args(argv)

    try:
        metadata = _read_json(args.metadata)
        version = _package_version()
        content = render(metadata, version)
    except MetadataError as exc:
        print(f"build_readme: {exc}", file=sys.stderr)
        return 2

    if args.stdout:
        sys.stdout.write(content)
        return 0

    if args.check:
        try:
            current = args.output.read_text(encoding="utf-8")
        except FileNotFoundError:
            current = None
        if current != content:
            print(
                f"build_readme: {args.output.name} is out of date. "
                "Run python3 scripts/build_readme.py and commit the result.",
                file=sys.stderr,
            )
            return 1
        return 0

    _write_atomic(args.output, content)
    print(f"build_readme: wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
